def t(first, second):
    """将'第一，A。第二，B。'转为'首先是A。其次，B。'"""
    trans = ["首先是","其次，","接着，","然后，","此外，","还有，","另外，","再者，","还有，","另外，"]
    for i, w in enumerate(trans):
        n = ["一","二","三","四","五","六","七","八","九","十"][i]
        first = re.sub(f'第{n}[项条]?[，,]', w, first)
        if second:
            second = re.sub(f'第{n}[项条]?[，,]', w, second)
    return first, second

def c(text):
    """清理无用后缀"""
    text = re.sub(r'[，,]\s*即时执行', '', text)
    text = re.sub(r'[，,]\s*即时[。]?', '，立即执行。', text)
    text = re.sub(r'，\s*达标即发(?!布)', '，达标即发布', text)
    text = re.sub(r'，\s*持续监测', '，需要持续监测', text)
    text = re.sub(r'，\s*持续[监控研判]', '，需要持续进行', text)
    text = re.sub(r'，\s*预备执行', '，需预先准备', text)
    text = re.sub(r'，\s*灾后执行', '，在灾后实施', text)
    text = re.sub(r'，每\d+小时\d*次', '，需定期更新', text)
    text = re.sub(r'，\d+小时内完成', '，需在规定时间内完成', text)
    text = re.sub(r'，\d+分钟\s*响应', '，需快速响应', text)
    text = re.sub(r'，\d+分鐘\s*直报', '，需第一时间直报', text)
    text = re.sub(r'二十四小时在岗', '全天候在岗', text)
    text = re.sub(r'二十四小时加强', '全天候加强', text)
    text = re.sub(r'二十四小时值班', '全天候值班', text)
    text = re.sub(r'。{2,}', '。', text)
    return text

def sop(text):
    """口语化SOP文本（第一→首先, 第二→其次...）"""
    trans = ["首先是","其次，","接着，","然后，","此外，","还有，","另外，","再者，","最后是，"]
    nums = ["一","二","三","四","五","六","七","八","九","十"]
    for i in range(len(nums)):
        text = re.sub(f'第{nums[i]}[项条]?[，,]\s*', trans[min(i,len(trans)-1)], text)
    return c(text)

def org(text):
    """清理组织指挥体系文本"""
    text = re.sub(r'\n{2,}', '。', text)
    text = re.sub(r'\n', '，', text)
    text = re.sub(r'。{2,}', '。', text)
    return text

def obj(text):
    """学习目标"""
    text = re.sub(r'^本章学习目标包括：', '本章学习目标是，', text)
    return text

def sec(title, content):
    """处理一个小节"""
    if 'SOP' in title:
        content = sop(content)  # sop内部已调用c()
    elif '组织指挥' in title or '体系' in title:
        content = c(org(content))
    elif '学习目标' in title:
        content = c(obj(content))
    else:
        content = c(content)
    return {"title": title, "content": content}

