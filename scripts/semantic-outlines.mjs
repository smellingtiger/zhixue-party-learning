import fs from 'fs';
import path from 'path';

const STT_BASE_DIR = 'E:\\社院课程stt';

function readTranscript(category, filename) {
  const filePath = path.join(STT_BASE_DIR, category, 'output_funasr', filename);
  return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

function writeSemanticOutlines(courseId, category, filename, segments) {
  const transcript = readTranscript(category, filename);
  const outlines = segments.map((seg, i) => {
    const startPara = transcript[seg.start - 1];
    const endPara = transcript[seg.end - 1];
    return {
      index: i + 1,
      start_time_second: startPara.start_time_second,
      end_time_second: endPara.end_time_second,
      summary: seg.summary
    };
  });

  const outlinePath = path.join(STT_BASE_DIR, category, 'output_outline', filename);
  fs.writeFileSync(outlinePath, JSON.stringify(outlines, null, 2), 'utf-8');
  console.log(`✓ ${courseId}: ${segments.length}段 (原${transcript.length}段→${segments.length}段)`);
}

