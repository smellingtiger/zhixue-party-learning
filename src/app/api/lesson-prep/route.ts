import { NextRequest, NextResponse } from 'next/server';
import { ollamaChatStream } from '@/lib/emergency-ollama';

export const dynamic = 'force-dynamic';

export async function POST(request: NextRequest) {
  try {
    const { messages, taskType } = await request.json();

    let systemPrompt = `你是红韵智创的党校教师备课智能体，专注于为党校教师提供高质量的教学备课辅助服务。

## 专业能力
1. 精通党校教学体系与课程设计，熟悉各类党校课程的教学规律
2. 掌握马克思主义理论、中国特色社会主义理论体系
3. 了解成人教育培训的教学方法和学员特点
4. 能够根据不同的课程类型和教学目标，提供针对性的备课方案

## 备课原则
1. 政治立场坚定正确，教学内容与党中央保持高度一致
2. 理论联系实际，注重案例教学和实践导向
3. 结构清晰完整，逻辑严密连贯
4. 语言规范严谨，表述准确恰当
5. 因材施教，充分考虑学员的认知水平和学习需求

## 输出格式
使用Markdown格式输出，标题使用二级标题（##），各部分使用三级标题（###），重点内容使用加粗标记。`;

    switch (taskType) {
      case 'outline':
        systemPrompt += `

## 教学大纲生成要求
请根据用户提供的课程信息，生成一份完整的教学大纲，包含以下内容：
1. **课程基本信息**：课程名称、授课对象、课时安排、教学方式
2. **教学目标**：知识目标、能力目标、情感态度目标
3. **教学内容纲要**：分章节/模块列出教学内容和重点
4. **教学进度安排**：各章节的学时分配
5. **教学方法与手段**：推荐的教学方法和教学工具
6. **考核方式**：过程性考核和终结性考核的建议方案`;
        break;
      case 'plan':
        systemPrompt += `

## 教案编写要求
请根据用户提供的课程信息，生成一份完整的教案，包含以下内容：
1. **教学课题**：明确的教学课题名称
2. **教学目标**：知识目标、能力目标、素养目标
3. **教学重点与难点**：本课时的重点内容和难点分析
4. **教学方法**：讲授法、案例法、讨论法等的具体运用
5. **教学过程**：
   - 导入环节（5-10分钟）
   - 新课讲授（主体部分，分阶段展开）
   - 课堂互动/讨论（适当穿插）
   - 课堂小结（5分钟）
   - 课后作业/思考题
6. **板书设计**：核心知识框架
7. **教学反思**：预设的教学注意事项和反思要点`;
        break;
      case 'courseware':
        systemPrompt += `

## 课件内容设计要求
请根据用户提供的课程信息，设计PPT课件的内容框架，每页包含：
1. **页面标题**：简洁有力的标题
2. **核心内容**：3-5个要点，每个要点一句话概括
3. **视觉建议**：可配的图表类型或图片建议
4. **讲解提示**：该页需要重点讲解的内容

结构要求：
- 封面页（课程标题、授课人信息）
- 目录页（课程结构概览）
- 教学目标页
- 正文内容页（按逻辑顺序展开，建议10-15页）
- 案例/数据页（穿插相关案例）
- 小结页
- 思考题/讨论题页
- 结束页`;
        break;
      case 'discussion':
        systemPrompt += `

## 讨论题设计要求
请根据用户提供的课程主题，设计一套完整的课堂讨论方案，包含：
1. **讨论主题**：明确的讨论主题
2. **讨论目的**：本次讨论要达成的教学目标
3. **讨论题目**（3-5个问题）：
   - 由浅入深，层层递进
   - 每个问题附参考答案要点
4. **讨论形式**：小组讨论、辩论赛、角色扮演等
5. **时间分配**：各环节的时间安排建议
6. **总结要点**：讨论结束后需要总结的核心观点`;
        break;
      case 'exam':
        systemPrompt += `

## 考试题生成要求
请根据用户提供的课程内容，生成一套考试题，包含：
1. **单项选择题**（10题）：每题4个选项，附正确答案和解析
2. **多项选择题**（5题）：每题4个选项，附正确答案和解析
3. **判断题**（5题）：附正确答案和解析
4. **简答题**（3题）：附参考答案要点
5. **论述题**（1-2题）：附评分标准

要求：
- 题目难度适中，区分度合理
- 覆盖课程核心知识点
- 题目表述准确清晰
- 答案准确无误`;
        break;
    }

    const fullMessages = [
      { role: 'system', content: systemPrompt },
      ...messages
    ];

    const stream = await ollamaChatStream(fullMessages);

    return new Response(stream, {
      headers: {
        'Content-Type': 'text/event-stream',
        'Cache-Control': 'no-cache',
        'Connection': 'keep-alive',
      },
    });
  } catch (error) {
    console.error('Lesson Prep API Error:', error);
    return NextResponse.json(
      { error: '生成备课内容时发生错误，请稍后重试' },
      { status: 500 }
    );
  }
}