function buildKnowledgeCandidates(value?: string | null): string[] {
  if (!value) return [];

  const trimmed = value.trim();
  if (!trimmed) return [];

  const baseName = trimmed
    .split(/[\\/]/)
    .pop()
    ?.replace(/\.[^.]+$/, '') || trimmed;

  return [...new Set([
    trimmed,
    baseName,
    trimmed.toUpperCase(),
    baseName.toUpperCase(),
  ])];
}

export function resolveKnowledgeVideoId(...values: Array<string | null | undefined>): string | null {
  for (const value of values) {
    for (const candidate of buildKnowledgeCandidates(value)) {
      const videoId = systemIdToVideoId[candidate];
      if (videoId) {
        return videoId;
      }
    }
  }

  return null;
}

